# Generates R/mlt_child.R (1q0 and 4q1 of the UN 2011 model life tables) from
# unpd_2011_mlt_130_1y_abridged.xlsx
# (https://www.un.org/development/desa/pd/data/model-life-tables).
# Run from the package root: Rscript data-raw/mlt.R
library(data.table)
library(readxl)

raw <- as.data.table(read_excel("unpd_2011_mlt_130_1y_abridged.xlsx", sheet = 1))
families <- c(North = "North", South = "South", East = "East", West = "West",
              Latin = "Latam", Chilean = "Chilean", South_Asian = "SAsia",
              Far_East_Asian = "FarEast", General = "General")

# l(1) and l(5) per 1 (radix 100000 in the file); l(5) = l(1) * (1 - 4q1).
lx <- raw[age %in% c(0, 1), .(l1 = 1 - qxn[age == 0],
                               l5 = (1 - qxn[age == 0]) * (1 - qxn[age == 1])),
          by = .(family = families[Family], sex = tolower(Sex), e0 = E0)]

# Both sexes: males and females of the same level combined with a sex ratio at birth of 1.05.
both <- dcast(lx, family + e0 ~ sex, value.var = c("l1", "l5"))
both <- both[, .(family, sex = "both", e0,
                 l1 = (1.05 * l1_male + l1_female) / 2.05,
                 l5 = (1.05 * l5_male + l5_female) / 2.05)]

mlt <- rbind(lx, both)[, .(family, sex, e0, q1 = 1 - l1, q4 = 1 - l5 / l1)]
setorder(mlt, family, sex, e0)
stopifnot(nrow(mlt) == 9 * 3 * 81, !anyNA(mlt))

fmt <- function(v) paste(sprintf("%.8g", v), collapse = ", ")
keys <- unique(mlt[, .(family, sex)])
body <- vapply(seq_len(nrow(keys)), function(k) {
  s <- mlt[family == keys$family[k] & sex == keys$sex[k]]
  sprintf('  data.table::data.table(family = "%s", sex = "%s", e0 = %d:%d,\n    q1 = c(%s),\n    q4 = c(%s))',
          keys$family[k], keys$sex[k], min(s$e0), max(s$e0), fmt(s$q1), fmt(s$q4))
}, character(1))
writeLines(c(
  "# Generated by data-raw/mlt.R from unpd_2011_mlt_130_1y_abridged.xlsx -- do not edit by hand.",
  "# UN Population Division (2011) model life tables: 1q0 (q1) and 4q1 (q4) by family, sex and",
  "# level e0 (20-100). \"both\" combines males and females of the same level with SRB = 1.05.",
  ".mlt_child <- data.table::rbindlist(list(",
  paste(body, collapse = ",\n"),
  "))"
), "R/mlt_child.R")
message("Wrote R/mlt_child.R with ", nrow(mlt), " rows")
