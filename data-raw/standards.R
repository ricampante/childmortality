# Generates R/sysdata_tables.R (standard logits Ys(x), e0 = 60) from GE_standards_0.xlsx.
# Run from the package root: Rscript data-raw/standards.R
library(data.table)
library(readxl)

raw <- suppressMessages(as.data.table(
  read_excel("GE_standards_0.xlsx", sheet = "Mortality standard logits", col_names = FALSE)
))
raw <- raw[, lapply(.SD, as.character)]

families <- c("Princeton North" = "North", "Princeton South" = "South",
              "Princeton East" = "East", "Princeton West" = "West",
              "UN General" = "General", "UN Latin America" = "Latam",
              "UN Chile" = "Chilean", "UN South Asia" = "SAsia",
              "UN Far East" = "FarEast")
sexes <- c(Males = "male", Females = "female", Combined = "both")

x_rows <- which(grepl("^[0-9]+$", raw[[1]]))
x <- as.integer(raw[[1]][x_rows])

out <- list()
for (j in seq_along(raw)[-1]) {
  sex_pos <- match(raw[[j]][3], names(sexes))
  if (is.na(sex_pos)) next
  fam_col <- j - (sex_pos - 1L)
  if (!raw[[fam_col]][2] %in% names(families)) next
  out[[length(out) + 1L]] <- data.table(
    family = families[[raw[[fam_col]][2]]],
    sex    = sexes[[raw[[j]][3]]],
    x      = x,
    ys     = as.numeric(raw[[j]][x_rows])
  )
}
std <- rbindlist(out)[!is.na(ys)]
stopifnot(nrow(std) == length(families) * length(sexes) * (length(x) - 1L))

fmt <- function(v) paste(sprintf("%.15g", v), collapse = ", ")
lines <- c(
  "# Generated by data-raw/standards.R from GE_standards_0.xlsx -- do not edit by hand.",
  "# Brass standard logits Ys(x) = 0.5 * log((1 - l(x)) / l(x)) for life tables with e0 = 60.",
  ".std_logits <- data.table::rbindlist(list("
)
keys <- unique(std[, .(family, sex)])
body <- vapply(seq_len(nrow(keys)), function(k) {
  s <- std[family == keys$family[k] & sex == keys$sex[k]]
  sprintf('  data.table::data.table(family = "%s", sex = "%s",\n    x = c(%s),\n    ys = c(%s))',
          keys$family[k], keys$sex[k], fmt(s$x), fmt(s$ys))
}, character(1))
lines <- c(lines, paste(body, collapse = ",\n"), "))")
writeLines(lines, "R/sysdata_tables.R")
message("Wrote R/sysdata_tables.R with ", nrow(std), " rows")
